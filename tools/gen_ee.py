#!/usr/bin/env python3
"""Generate the R5900-specific SLEIGH of this module (Ghidra-Rare).

  gen_ee.py lanes   > data/languages/lanes.sinc    lane registers and lane operand subtables
  gen_ee.py eecore  > data/languages/eecore.sinc   EE core-specific instructions (MMI, SA, LQ/SQ, pipeline 1)
  gen_ee.py vu      > data/languages/vu.sinc       COP2: VU0 macro-mode instructions and transfers

The upstream module (chaoticgd/ghidra-emotionengine-reloaded) implements the MMI and VU macro
instructions as pcodeop stubs. Ghidra-Rare gives them p-code semantics lane by lane. To keep the
p-code small, every 128-bit register (GPRs, HI/LO, VU vf registers, ACC) is also defined as byte /
halfword / word / doubleword lane registers, and every lane of an rs / rt / rd field has its own
operand subtable; a source lane of register 0 is the constant 0 (the hardware discards writes to
$zero, so a write to a zero lane can never be observed).

Instruction semantics follow the EE Core Instruction Set Manual's descriptions of the instructions
(as summarised in GHIDRA-RARE.md); the encodings follow the reference disassemblers used by the
test suite (GNU objdump -m mips:5900 and rabbitizer, both run as black boxes).
"""
import sys

GPR = ['zero', 'at', 'v0', 'v1', 'a0', 'a1', 'a2', 'a3', 't0', 't1', 't2', 't3', 't4', 't5', 't6', 't7',
       's0', 's1', 's2', 's3', 's4', 's5', 's6', 's7', 't8', 't9', 'k0', 'k1', 'gp', 'sp', 's8', 'ra']
FIELDS = {'rs': (21, 25), 'rt': (16, 20), 'rd': (11, 15)}
LANES = {'b': 16, 'h': 8, 'w': 4, 'd': 2}
LSIZE = {'b': 1, 'h': 2, 'w': 4, 'd': 8}
XYZW = 'xyzw'


def lane_name(base, kind, i):
    """Register name of lane i of a 128-bit register (re-using the upstream 64/32-bit names)."""
    if kind == 'd':
        if base in ('hi', 'lo'):
            return [base, base + '1'][i]
        return [base, base + '_udw'][i]
    if kind == 'w' and i < 2 and base not in ('hi', 'lo'):
        return [base + '_lo', base + '_hi'][i]
    return f'{base}_{kind}{i}'


def lanes():
    o = []
    w = o.append
    w('# Generated by tools/gen_ee.py lanes: do not edit.')
    w('# Lane views of the 128-bit registers (the 64-bit and the low 32-bit names are defined in base.sinc).')
    for kind in 'bhw':
        n, size = LANES[kind], LSIZE[kind]
        names = []
        for r in GPR:
            for i in range(n):
                nm = lane_name(r, kind, i)
                names.append('_' if (kind == 'w' and i < 2) else nm)
        w(f'define register offset=0 size={size} [')
        for k in range(0, len(names), 16):
            w('    ' + ' '.join(names[k:k + 16]))
        w('];')
    # HI / LO: hi_qw at 0x300, lo_qw at 0x310; the 64-bit views hi hi1 lo lo1 are in base.sinc
    for kind in 'bhw':
        n, size = LANES[kind], LSIZE[kind]
        names = [lane_name(r, kind, i) for r in ('hi', 'lo') for i in range(n)]
        w(f'define register offset=0x300 size={size} [ ' + ' '.join(names) + ' ];')
    w('')
    for f in FIELDS:
        for kind in 'bhwd':
            for i in range(LANES[kind]):
                regs = [lane_name(r, kind, i) for r in GPR]
                w(f'attach variables [ {f}_{kind}{i} ] [ ' + ' '.join(regs) + ' ];')
    w('')
    w('# Source lanes: register 0 reads as 0.')
    for f in ('rs', 'rt'):
        for kind in 'bhwd':
            for i in range(LANES[kind]):
                sub = f'{f.upper()}{kind}{i}'
                w(f'{sub}: {f}_{kind}{i} is {f}_{kind}{i} & {f}=0 {{ export 0:{LSIZE[kind]}; }}')
                w(f'{sub}: {f}_{kind}{i} is {f}_{kind}{i} {{ export {f}_{kind}{i}; }}')
    return '\n'.join(o) + '\n'


def lanefields():
    o = ['# Generated by tools/gen_ee.py lanefields: do not edit. (Included inside base.sinc\'s instr token.)']
    for f, (lo, hi) in FIELDS.items():
        for kind in 'bhwd':
            for i in range(LANES[kind]):
                o.append(f'    {f}_{kind}{i} = ({lo},{hi})')
    for f, (lo, hi) in (('vft', (16, 20)), ('vfs', (11, 15)), ('vfd', (6, 10))):
        for c in XYZW:
            o.append(f'    {f}_{c} = ({lo},{hi})')
    return '\n'.join(o) + '\n'


# ----------------------------------------------------------------------------------------------------
# EE core-specific instructions
# ----------------------------------------------------------------------------------------------------

class Gen:
    def __init__(self):
        self.out = []

    def w(self, s=''):
        self.out.append(s)

    LANE_OPS = __import__('re').compile(
        r'\b(r[sdt]_[bhwd]\d+|R[ST][bhwd]\d+|VF[ST][xyzw]|WF[STD][xyzw]|R(?:IS|IT|CC)|W(?:IS|IT|ID|CC)|BCT|FSF|FTF|vudest)\b')

    def con(self, display, pattern, body):
        have = set(__import__('re').findall(r'\w+', pattern))
        for name in dict.fromkeys(self.LANE_OPS.findall(' '.join(body))):
            if name not in have:
                pattern += ' & ' + name
                have.add(name)
        self.w(f':{display} is {pattern} {{')
        for line in body:
            self.w('    ' + line)
        self.w('}')


def S(f, kind, i):   # source lane
    return f'{f.upper()}{kind}{i}'


def D(kind, i):      # destination lane of rd
    return f'rd_{kind}{i}'


def HL(r, kind, i):  # HI/LO lane
    return lane_name(r, kind, i)


MAXS = {1: '0x7f', 2: '0x7fff', 4: '0x7fffffff'}
MINS = {1: '0x80', 2: '0x8000', 4: '0x80000000'}
UMAX = {1: '0xff', 2: '0xffff', 4: '0xffffffff'}


def eecore():
    g = Gen()
    w = g.w
    w('# Generated by tools/gen_ee.py eecore: do not edit.')
    w('# EE core-specific instructions: the 128-bit loads and stores, the SA register, the pipeline-1')
    w('# multiply/divide unit (HI1/LO1) and the multimedia instructions (MMI), with lane-by-lane p-code.')
    w('')
    w('define register offset=0x400 size=8 [ fsa ];   # SA: the funnel shift amount, in bits (0..127)')
    w('')
    # ------------------------------------------------------------------ LQ / SQ: address bits 3..0 ignored
    w('# LQ / SQ ignore the low four address bits (the access is always 16-byte aligned).')
    g.con('lq RT128, OFF_BASE', 'prime=30 & OFF_BASE & RT128 & RT',
          ['ea:4 = OFF_BASE & 0xfffffff0;'] +
          [f'rt_w{i} = *[ram]:4 (ea + {4 * i});' for i in range(4)])
    g.con('sq RT128src, OFF_BASE', 'prime=31 & OFF_BASE & RT128src',
          ['ea:4 = OFF_BASE & 0xfffffff0;'] +
          [f'*[ram]:4 (ea + {4 * i}) = RTw{i};' for i in range(4)])
    # ------------------------------------------------------------------ SA register
    g.con('mfsa RD', 'prime=0 & rs=0 & rt=0 & sa=0 & fct=40 & RD', ['RD = fsa;'])
    g.con('mtsa RSsrc', 'prime=0 & rt=0 & rd=0 & sa=0 & fct=41 & RSsrc', ['fsa = RSsrc & 0x7f;'])
    g.con('mtsab RSsrc, simmed', 'prime=1 & copfct=24 & RSsrc & simmed',
          ['fsa = ((RSsrc ^ simmed) & 0xf) * 8;'])
    g.con('mtsah RSsrc, simmed', 'prime=1 & copfct=25 & RSsrc & simmed',
          ['fsa = ((RSsrc ^ simmed) & 0x7) * 16;'])
    # ------------------------------------------------------------------ 3-operand MULT/MULTU (pipeline 0)
    w('')
    w('# MULT/MULTU with rd: rd also receives LO. (rd = 0 is the plain MIPS form in mips.sinc.)')
    for nm, ext, f in (('mult', 'sext', 24), ('multu', 'zext', 25)):
        g.con(f'{nm} RD, RS32src, RT32src', f'prime=0 & sa=0 & fct={f} & RD & RS32src & RT32src',
              [f'prod:8 = {ext}(RS32src) * {ext}(RT32src);', 'lo = sext(prod:4);', 'hi = sext(prod[32,32]);',
               'RD = lo;'])
    # ------------------------------------------------------------------ MMI (prime 28)
    w('')
    w('with : prime=28 {')
    w('')
    # pipeline-0 / pipeline-1 multiply-add
    for suffix, H, L in (('', 'hi', 'lo'), ('1', 'hi1', 'lo1')):
        for nm, ext, f, op in (('madd', 'sext', 0, '+'), ('maddu', 'zext', 1, '+')):
            fct = f + (32 if suffix else 0)
            body = [f'acc:8 = (zext({H}:4) << 32) | zext({L}:4);',
                    f'acc = acc {op} ({ext}(RS32src) * {ext}(RT32src));',
                    f'{L} = sext(acc:4);', f'{H} = sext(acc[32,32]);']
            g.con(f'{nm}{suffix} RS32src, RT32src', f'rd=0 & sa=0 & fct={fct} & RS32src & RT32src', body)
            g.con(f'{nm}{suffix} RD, RS32src, RT32src', f'sa=0 & fct={fct} & RD & RS32src & RT32src',
                  body + [f'RD = {L};'])
    for nm, ext, f in (('mult1', 'sext', 24), ('multu1', 'zext', 25)):
        body = [f'prod:8 = {ext}(RS32src) * {ext}(RT32src);', 'lo1 = sext(prod:4);', 'hi1 = sext(prod[32,32]);']
        g.con(f'{nm} RS32src, RT32src', f'rd=0 & sa=0 & fct={f} & RS32src & RT32src', body)
        g.con(f'{nm} RD, RS32src, RT32src', f'sa=0 & fct={f} & RD & RS32src & RT32src', body + ['RD = lo1;'])
    g.con('div1 RS32src, RT32src', 'rd=0 & sa=0 & fct=26 & RS32src & RT32src',
          ['lo1 = sext(RS32src s/ RT32src);', 'hi1 = sext(RS32src s% RT32src);'])
    g.con('divu1 RS32src, RT32src', 'rd=0 & sa=0 & fct=27 & RS32src & RT32src',
          ['lo1 = sext(RS32src / RT32src);', 'hi1 = sext(RS32src % RT32src);'])
    g.con('mfhi1 RD', 'rs=0 & rt=0 & sa=0 & fct=16 & RD', ['RD = hi1;'])
    g.con('mthi1 RSsrc', 'rt=0 & rd=0 & sa=0 & fct=17 & RSsrc', ['hi1 = RSsrc;'])
    g.con('mflo1 RD', 'rs=0 & rt=0 & sa=0 & fct=18 & RD', ['RD = lo1;'])
    g.con('mtlo1 RSsrc', 'rt=0 & rd=0 & sa=0 & fct=19 & RSsrc', ['lo1 = RSsrc;'])
    g.con('plzcw RD, RSsrc', 'rt=0 & sa=0 & fct=4 & RD & RSsrc',
          [f'x{i}:4 = RSw{i};' for i in range(2)] +
          [f'rd_w{i} = lzcount(x{i} ^ (x{i} s>> 31)) - 1;' for i in range(2)])
    # shifts by immediate (sa field): halfword shifts use sa[3:0]
    for nm, f, kind, op in (('psllh', 0x34, 'h', '<<'), ('psrlh', 0x36, 'h', '>>'), ('psrah', 0x37, 'h', 's>>'),
                            ('psllw', 0x3c, 'w', '<<'), ('psrlw', 0x3e, 'w', '>>'), ('psraw', 0x3f, 'w', 's>>')):
        amt = 'sa & 0xf' if kind == 'h' else 'sa'
        g.con(f'{nm} RD128, RT128src, sa', f'rs=0 & fct={f} & sa & RD128 & RT128src',
              [f's:{LSIZE[kind]} = {amt};'] + [f'{D(kind, i)} = {S("rt", kind, i)} {op} s;' for i in range(LANES[kind])])
    # ------------------------------------------------------------------ MMI0 (fct 8), MMI1 (40), MMI2 (9), MMI3 (41)
    mmi = []

    def M(fct, sub, name, operands, body, fixed=''):
        mmi.append((fct, sub, name, operands, body, fixed))

    def lanewise(kind, expr):
        return [f'{D(kind, i)} = {expr.format(s=S("rs", kind, i), t=S("rt", kind, i))};' for i in range(LANES[kind])]

    def sat_s(kind, op):
        n = LSIZE[kind]
        body = []
        for i in range(LANES[kind]):
            body += [f'r{i}:{2 * n} = sext({S("rs", kind, i)}) {op} sext({S("rt", kind, i)});',
                     f'p{i}:1 = r{i} s> {MAXS[n]}; m{i}:1 = r{i} s< -{int(MINS[n], 16)};',
                     f'{D(kind, i)} = (zext(p{i}) * {MAXS[n]}) | (zext(m{i}) * {MINS[n]}) | '
                     f'(zext(!(p{i} || m{i})) * r{i}:{n});']
        return body

    def sat_u_add(kind):
        n = LSIZE[kind]
        body = []
        for i in range(LANES[kind]):
            body += [f'r{i}:{2 * n} = zext({S("rs", kind, i)}) + zext({S("rt", kind, i)});',
                     f'p{i}:1 = r{i} > {UMAX[n]};',
                     f'{D(kind, i)} = (zext(p{i}) * {UMAX[n]}) | (zext(!p{i}) * r{i}:{n});']
        return body

    def sat_u_sub(kind):
        body = []
        for i in range(LANES[kind]):
            s, t = S('rs', kind, i), S('rt', kind, i)
            body += [f'{D(kind, i)} = zext({s} > {t}) * ({s} - {t});']
        return body

    def cmp(kind, op):
        return [f'{D(kind, i)} = 0 - zext({S("rs", kind, i)} {op} {S("rt", kind, i)});' for i in range(LANES[kind])]

    def minmax(kind, op):
        out = []
        for i in range(LANES[kind]):
            s, t = S('rs', kind, i), S('rt', kind, i)
            out.append(f'{D(kind, i)} = (zext({s} {op} {t}) * {s}) | (zext(!({s} {op} {t})) * {t});')
        return out

    def ext_lower(kind, upper):
        n = LANES[kind] // 2
        out = []
        for i in range(n):
            j = i + (n if upper else 0)
            out.append(f'tp{2 * i}:{LSIZE[kind]} = {S("rt", kind, j)};')
            out.append(f'tp{2 * i + 1}:{LSIZE[kind]} = {S("rs", kind, j)};')
        out += [f'{D(kind, k)} = tp{k};' for k in range(2 * n)]
        return out

    def pack(kind):
        n = LANES[kind]
        out = [f'tp{i}:{LSIZE[kind]} = {S("rt", kind, 2 * i)};' for i in range(n // 2)]
        out += [f'tp{n // 2 + i}:{LSIZE[kind]} = {S("rs", kind, 2 * i)};' for i in range(n // 2)]
        out += [f'{D(kind, i)} = tp{i};' for i in range(n)]
        return out

    def absl(kind):
        n = LSIZE[kind]
        out = []
        for i in range(LANES[kind]):
            t = S('rt', kind, i)
            out.append(f'm{i}:1 = {t} == {MINS[n]};')
            out.append(f'{D(kind, i)} = (zext(m{i}) * {MAXS[n]}) | (zext({t} s< 0 && !m{i}) * (0 - {t})) | '
                       f'(zext({t} s>= 0) * {t});')
        return out

    def perm(kind, src_of):
        """rd lane i = rt lane src_of[i]."""
        out = [f'tp{i}:{LSIZE[kind]} = {S("rt", kind, src_of[i])};' for i in range(LANES[kind])]
        return out + [f'{D(kind, i)} = tp{i};' for i in range(LANES[kind])]

    def logic(op, invert=False):
        out = []
        for i in range(2):
            e = f'{S("rs", "d", i)} {op} {S("rt", "d", i)}'
            out.append(f'rd_d{i} = {"~(" + e + ")" if invert else e};')
        return out

    # --- MMI0 (fct 8)
    M(8, 0x00, 'paddw', 'RD128, RS128src, RT128src', lanewise('w', '{s} + {t}'))
    M(8, 0x01, 'psubw', 'RD128, RS128src, RT128src', lanewise('w', '{s} - {t}'))
    M(8, 0x02, 'pcgtw', 'RD128, RS128src, RT128src', cmp('w', 's>'))
    M(8, 0x03, 'pmaxw', 'RD128, RS128src, RT128src', minmax('w', 's>='))
    M(8, 0x04, 'paddh', 'RD128, RS128src, RT128src', lanewise('h', '{s} + {t}'))
    M(8, 0x05, 'psubh', 'RD128, RS128src, RT128src', lanewise('h', '{s} - {t}'))
    M(8, 0x06, 'pcgth', 'RD128, RS128src, RT128src', cmp('h', 's>'))
    M(8, 0x07, 'pmaxh', 'RD128, RS128src, RT128src', minmax('h', 's>='))
    M(8, 0x08, 'paddb', 'RD128, RS128src, RT128src', lanewise('b', '{s} + {t}'))
    M(8, 0x09, 'psubb', 'RD128, RS128src, RT128src', lanewise('b', '{s} - {t}'))
    M(8, 0x0a, 'pcgtb', 'RD128, RS128src, RT128src', cmp('b', 's>'))
    M(8, 0x10, 'paddsw', 'RD128, RS128src, RT128src', sat_s('w', '+'))
    M(8, 0x11, 'psubsw', 'RD128, RS128src, RT128src', sat_s('w', '-'))
    M(8, 0x12, 'pextlw', 'RD128, RS128src, RT128src', ext_lower('w', False))
    M(8, 0x13, 'ppacw', 'RD128, RS128src, RT128src', pack('w'))
    M(8, 0x14, 'paddsh', 'RD128, RS128src, RT128src', sat_s('h', '+'))
    M(8, 0x15, 'psubsh', 'RD128, RS128src, RT128src', sat_s('h', '-'))
    M(8, 0x16, 'pextlh', 'RD128, RS128src, RT128src', ext_lower('h', False))
    M(8, 0x17, 'ppach', 'RD128, RS128src, RT128src', pack('h'))
    M(8, 0x18, 'paddsb', 'RD128, RS128src, RT128src', sat_s('b', '+'))
    M(8, 0x19, 'psubsb', 'RD128, RS128src, RT128src', sat_s('b', '-'))
    M(8, 0x1a, 'pextlb', 'RD128, RS128src, RT128src', ext_lower('b', False))
    M(8, 0x1b, 'ppacb', 'RD128, RS128src, RT128src', pack('b'))
    ext5 = []
    pac5 = []
    for i in range(4):
        t = S('rt', 'w', i)
        ext5.append(f'x{i}:4 = {t};')
        ext5.append(f'rd_w{i} = ((x{i} & 0x1f) << 3) | ((x{i} & 0x3e0) << 6) | ((x{i} & 0x7c00) << 9) | '
                    f'((x{i} & 0x8000) << 16);')
        pac5.append(f'x{i}:4 = {t};')
        pac5.append(f'rd_w{i} = ((x{i} >> 3) & 0x1f) | ((x{i} >> 6) & 0x3e0) | ((x{i} >> 9) & 0x7c00) | '
                    f'((x{i} >> 16) & 0x8000);')
    M(8, 0x1e, 'pext5', 'RD128, RT128src', ext5, 'rs=0')
    M(8, 0x1f, 'ppac5', 'RD128, RT128src', pac5, 'rs=0')
    # --- MMI1 (fct 40)
    M(40, 0x01, 'pabsw', 'RD128, RT128src', absl('w'), 'rs=0')
    M(40, 0x02, 'pceqw', 'RD128, RS128src, RT128src', cmp('w', '=='))
    M(40, 0x03, 'pminw', 'RD128, RS128src, RT128src', minmax('w', 's<='))
    padsbh = [f'rd_h{i} = {S("rs", "h", i)} - {S("rt", "h", i)};' for i in range(4)]
    padsbh += [f'rd_h{i} = {S("rs", "h", i)} + {S("rt", "h", i)};' for i in range(4, 8)]
    M(40, 0x04, 'padsbh', 'RD128, RS128src, RT128src', padsbh)
    M(40, 0x05, 'pabsh', 'RD128, RT128src', absl('h'), 'rs=0')
    M(40, 0x06, 'pceqh', 'RD128, RS128src, RT128src', cmp('h', '=='))
    M(40, 0x07, 'pminh', 'RD128, RS128src, RT128src', minmax('h', 's<='))
    M(40, 0x0a, 'pceqb', 'RD128, RS128src, RT128src', cmp('b', '=='))
    M(40, 0x10, 'padduw', 'RD128, RS128src, RT128src', sat_u_add('w'))
    M(40, 0x11, 'psubuw', 'RD128, RS128src, RT128src', sat_u_sub('w'))
    M(40, 0x12, 'pextuw', 'RD128, RS128src, RT128src', ext_lower('w', True))
    M(40, 0x14, 'padduh', 'RD128, RS128src, RT128src', sat_u_add('h'))
    M(40, 0x15, 'psubuh', 'RD128, RS128src, RT128src', sat_u_sub('h'))
    M(40, 0x16, 'pextuh', 'RD128, RS128src, RT128src', ext_lower('h', True))
    M(40, 0x18, 'paddub', 'RD128, RS128src, RT128src', sat_u_add('b'))
    M(40, 0x19, 'psubub', 'RD128, RS128src, RT128src', sat_u_sub('b'))
    M(40, 0x1a, 'pextub', 'RD128, RS128src, RT128src', ext_lower('b', True))
    # QFSRV: rd = ({rs, rt} >> SA)[127:0], built from 64-bit pieces
    qf = ['sh:8 = fsa & 0x7f;',
          'tp0:8 = RTd0; tp1:8 = RTd1; tp2:8 = RSd0; tp3:8 = RSd1;',
          'q:8 = sh >> 6; b:8 = sh & 0x3f;',
          '# select the 64-bit pieces starting at piece q, then shift the 128-bit window right by b bits',
          'sel0:8 = (zext(q == 0) * tp0) | (zext(q == 1) * tp1);',
          'sel1:8 = (zext(q == 0) * tp1) | (zext(q == 1) * tp2);',
          'sel2:8 = (zext(q == 0) * tp2) | (zext(q == 1) * tp3);',
          'nb:8 = (64 - b) & 0x3f; nz:8 = zext(b != 0);',
          'rd_d0 = (sel0 >> b) | ((sel1 << nb) * nz);',
          'rd_d1 = (sel1 >> b) | ((sel2 << nb) * nz);']
    M(40, 0x1b, 'qfsrv', 'RD128, RS128src, RT128src', qf)
    # --- MMI2 (fct 9)
    def mul_w(signed, acc):
        ext = 'sext' if signed else 'zext'
        out = []
        for i in range(2):
            s, t = S('rs', 'w', 2 * i), S('rt', 'w', 2 * i)
            hiw, low = HL('hi', 'w', 2 * i), HL('lo', 'w', 2 * i)
            hid, lod = HL('hi', 'd', i), HL('lo', 'd', i)
            prod = f'{ext}({s}) * {ext}({t})'
            if acc:
                out.append(f'p{i}:8 = ((zext({hiw}) << 32) | zext({low})) {acc} ({prod});')
            else:
                out.append(f'p{i}:8 = {prod};')
            out.append(f'{lod} = sext(p{i}:4); {hid} = sext(p{i}[32,32]);')
        out += [f'rd_d{i} = p{i};' for i in range(2)]
        return out

    def div_w(signed):
        out = []
        for i in range(2):
            s, t = S('rs', 'w', 2 * i), S('rt', 'w', 2 * i)
            q, r = ('s/', 's%') if signed else ('/', '%')
            out += [f'{HL("lo", "d", i)} = sext({s} {q} {t}); {HL("hi", "d", i)} = sext({s} {r} {t});']
        return out

