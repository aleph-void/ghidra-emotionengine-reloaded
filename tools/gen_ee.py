    for k, (nm, f) in enumerate((('vitof0', 0x13c), ('vitof4', 0x13d), ('vitof12', 0x13e), ('vitof15', 0x13f))):
        sc = [0, 16, 4096, 32768][k]
        pre = [] if not sc else [f'sc:4 = int2float({sc}:4);']
        ex = {c: (f'int2float(VFS{c})' if not sc else f'int2float(VFS{c}) f/ sc') for c in XYZW}
        U(f'{nm}^dest vuft, vufs', f'vuinst & dest & vuft & vufs & {fsl} & {ftw} & vuop_0_10={f}',
          masked('FT', ex, pre))
    for k, (nm, f) in enumerate((('vftoi0', 0x17c), ('vftoi4', 0x17d), ('vftoi12', 0x17e), ('vftoi15', 0x17f))):
        sc = [0, 16, 4096, 32768][k]
        pre = ['big:4 = int2float(0x80000000:8);']
        if sc:
            pre.append(f'sc:4 = int2float({sc}:4);')
        for c in XYZW:
            v = f'VFS{c}' if not sc else f'(VFS{c} f* sc)'
            pre += [f'f{c}:4 = {v};', f'h{c}:1 = f{c} f>= big; l{c}:1 = f{c} f< f- big;',
                    f'q{c}:4 = (zext(h{c}) * 0x7fffffff) | (zext(l{c}) * 0x80000000) | '
                    f'(zext(!(h{c} || l{c})) * trunc(f{c}));']
        U(f'{nm}^dest vuft, vufs', f'vuinst & dest & vuft & vufs & {fsl} & {ftw} & vuop_0_10={f}',
          masked('FT', {c: f'q{c}' for c in XYZW}, pre))
    U('vabs^dest vuft, vufs', f'vuinst & dest & vuft & vufs & {fsl} & {ftw} & vuop_0_10=0x1fd',
      masked('FT', {c: f'abs(VFS{c})' for c in XYZW}))
    U('vmove^dest vuft, vufs', f'vuinst & dest & vuft & vufs & {fsl} & {ftw} & vuop_0_10=0x33c',
      masked('FT', {c: f'VFS{c}' for c in XYZW}))
    rot = {'x': 'y', 'y': 'z', 'z': 'w', 'w': 'x'}
    U('vmr32^dest vuft, vufs', f'vuinst & dest & vuft & vufs & {fsl} & {ftw} & vuop_0_10=0x33d',
      masked('FT', {c: f'VFS{rot[c]}' for c in XYZW}))
    # clipping judgement against |ft.w|: clip flags shift up by 6, new flags +x -x +y -y +z -z in bits 0..5
    U('vclipw^dest vufs, vuft^"w"', 'vuinst & dest & vufs & vuft & VFSx & VFSy & VFSz & VFTw & vuop_0_10=0x1ff',
      ['wa:4 = abs(VFTw); wn:4 = f- wa;',
       'cf:4 = (vi18 << 6) & 0xffffff;',
       'vi18 = cf | zext(VFSx f> wa) | (zext(VFSx f< wn) << 1) | (zext(VFSy f> wa) << 2) | '
       '(zext(VFSy f< wn) << 3) | (zext(VFSz f> wa) << 4) | (zext(VFSz f< wn) << 5);'])
    # Q (division unit)
    U('vdiv "Q", vufs^fsf, vuft^ftf', 'vuinst & fsf & ftf & FSF & FTF & vufs & vuft & vuop_0_10=0x3bc',
      ['vi22 = FSF f/ FTF;'])
    U('vsqrt "Q", vuft^ftf', 'vuinst & ftf & FTF & vuft & vuop_0_10=0x3bd', ['vi22 = sqrt(abs(FTF));'])
    U('vrsqrt "Q", vufs^fsf, vuft^ftf', 'vuinst & fsf & ftf & FSF & FTF & vufs & vuft & vuop_0_10=0x3be',
      ['vi22 = FSF f/ sqrt(abs(FTF));'])
    U('vwaitq', 'vuinst & vuop_0_10=0x3bf', [])
    # integer <-> float register transfers
    U('vmtir WIT, vufs^fsf', 'vuinst & fsf & WIT & FSF & vufs & vuop_0_10=0x3fc', ['WIT = FSF & 0xffff;'])
    U('vmfir^dest vuft, RIS', f'vuinst & dest & vuft & RIS & {ftw} & vuop_0_10=0x3fd',
      masked('FT', {c: 'v' for c in XYZW}, ['v:4 = sext(RIS:2);']))
    # VU0 data memory: quadword address (vi & 0xff) in the 4 KiB VU0 data memory at 0x11004000
    qaddr = lambda r: f'{VU0_DATA:#x} + (({r} & 0xff) << 4)'
    for k, c in enumerate(XYZW):
        U(f'vilwr.{c} WIT, (RIS)', f'vuinst & vudest={1 << (3 - k)} & WIT & RIS & vuop_0_10=0x3fe',
          [f'a:4 = {qaddr("RIS")};', f'WIT = zext(*[ram]:2 (a + {4 * k}));'])
        U(f'viswr.{c} RIT, (RIS)', f'vuinst & vudest={1 << (3 - k)} & RIT & RIS & vuop_0_10=0x3ff',
          [f'a:4 = {qaddr("RIS")};', f'*[ram]:4 (a + {4 * k}) = RIT & 0xffff;'])
    U('vlqi^dest vuft, (RIS^"++")', f'vuinst & dest & vuft & RIS & WIS & {ftw} & vuop_0_10=0x37c',
      masked('FT', {c: f'*[ram]:4 (a + {4 * k})' for k, c in enumerate(XYZW)}, [f'a:4 = {qaddr("RIS")};']) +
      ['WIS = (RIS + 1) & 0xffff;'])
    U('vsqi^dest vufs, (RIT^"++")', f'vuinst & dest & vufs & RIT & WIT & {fsl} & vuop_0_10=0x37d',
      [f'a:4 = {qaddr("RIT")};', 'dm:1 = vudest;'] +
      [f'if ((dm & {1 << (3 - k)}) == 0) goto <s{c}>; *[ram]:4 (a + {4 * k}) = VFS{c}; <s{c}>'
       for k, c in enumerate(XYZW)] + ['WIT = (RIT + 1) & 0xffff;'])
    U('vlqd^dest vuft, ("--"^RIS)', f'vuinst & dest & vuft & RIS & WIS & {ftw} & vuop_0_10=0x37e',
      ['n:4 = (RIS - 1) & 0xffff;', 'WIS = n;'] +
      masked('FT', {c: f'*[ram]:4 (a + {4 * k})' for k, c in enumerate(XYZW)}, [f'a:4 = {qaddr("n")};']))
    U('vsqd^dest vufs, ("--"^RIT)', f'vuinst & dest & vufs & RIT & WIT & {fsl} & vuop_0_10=0x37f',
      ['n:4 = (RIT - 1) & 0xffff;', 'WIT = n;', f'a:4 = {qaddr("n")};', 'dm:1 = vudest;'] +
      [f'if ((dm & {1 << (3 - k)}) == 0) goto <s{c}>; *[ram]:4 (a + {4 * k}) = VFS{c}; <s{c}>'
       for k, c in enumerate(XYZW)])
    # random number register R (vi20): a 23-bit value presented as a float in [1.0, 2.0)
    U('vrnext^dest vuft, "R"', f'vuinst & dest & vuft & {ftw} & vuop_0_10=0x43c',
      ['vi20 = vrnext(vi20);'] + masked('FT', {c: 'rv' for c in XYZW}, ['rv:4 = (vi20 & 0x7fffff) | 0x3f800000;']))
    U('vrget^dest vuft, "R"', f'vuinst & dest & vuft & {ftw} & vuop_0_10=0x43d',
      masked('FT', {c: 'rv' for c in XYZW}, ['rv:4 = (vi20 & 0x7fffff) | 0x3f800000;']))
    U('vrinit "R", vufs^fsf', 'vuinst & fsf & FSF & vufs & vuop_0_10=0x43e', ['vi20 = (FSF & 0x7fffff) | 0x3f800000;'])
    U('vrxor "R", vufs^fsf', 'vuinst & fsf & FSF & vufs & vuop_0_10=0x43f',
      ['vi20 = ((vi20 ^ FSF) & 0x7fffff) | 0x3f800000;'])
    U('c2 imm25', 'prime=18 & vuco=1 & imm25', ['cop2Operation(imm25:4);'])
    # transfers ----------------------------------------------------------------------------------------
    w('')
    w('with : prime=18 {')
    for bc, (nm, t, likely) in enumerate((('bc2f', 0, 0), ('bc2t', 1, 0), ('bc2fl', 0, 1), ('bc2tl', 1, 1))):
        cond = 'c != 0' if t == 0 else 'c == 0'
        if likely:
            body = ['c:1 = vu0Condition();', f'if ({cond}) goto inst_next;', 'delayslot(1);', 'goto Rel16;']
        else:
            body = ['c:1 = vu0Condition();', 'delayslot(1);', f'if ({cond}) goto inst_next;', 'goto Rel16;']
        g.con(f'{nm} Rel16', f'vuop_21_25=8 & vuop_16_20={bc} & Rel16', body)
    g.con('qmfc2^I RT, vufs', f'vuop_21_25=1 & vuop_1_10=0 & I & RT & vufs & {fsl}',
          [f'rt_w{k} = VFS{c};' for k, c in enumerate(XYZW)])
    g.con('qmtc2^I RTsrc, vufs', f'vuop_21_25=5 & vuop_1_10=0 & I & RTsrc & vufs & {fsw}',
          [f'tp{k}:4 = RTw{k};' for k in range(4)] + [f'WFS{c} = tp{k};' for k, c in enumerate(XYZW)])
    g.con('cfc2^I RT, RCC', 'vuop_21_25=2 & vuop_1_10=0 & I & RT & RCC', ['RT = sext(RCC);'])
    g.con('ctc2^I RTsrc, WCC', 'vuop_21_25=6 & vuop_1_10=0 & I & RTsrc & WCC', ['WCC = RTsrc:4;'])
    w('}')
    w('')
    g.con('lqc2 vuft, OFF_BASE', f'prime=54 & OFF_BASE & vuft & {ftw}',
          ['ea:4 = OFF_BASE & 0xfffffff0;'] + [f'WFT{c} = *[ram]:4 (ea + {4 * k});' for k, c in enumerate(XYZW)])
    g.con('sqc2 vuft, OFF_BASE', f'prime=62 & OFF_BASE & vuft & {ftl}',
          ['ea:4 = OFF_BASE & 0xfffffff0;'] + [f'*[ram]:4 (ea + {4 * k}) = VFT{c};' for k, c in enumerate(XYZW)])
    return '\n'.join(g.out) + '\n'


