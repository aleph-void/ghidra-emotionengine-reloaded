def fmax(a, b):
    return f'(zext({a} f>= {b}) * {a}) | (zext({a} f< {b}) * {b})'


def fmin(a, b):
    return f'(zext({a} f<= {b}) * {a}) | (zext({a} f> {b}) * {b})'


def arith(nm, a, b, c):
    """Lane result of operation nm: fs lane a, second operand b, ACC lane c."""
    return {'add': f'{a} f+ {b}', 'sub': f'{a} f- {b}', 'mul': f'{a} f* {b}',
            'madd': f'{c} f+ ({a} f* {b})', 'msub': f'{c} f- ({a} f* {b})',
            'max': fmax(a, b), 'mini': fmin(a, b)}[nm]


def masked(target, exprs, pre=(), lanes=XYZW):
    """Write exprs[c] to the dest-selected lanes of target ('FD', 'FT', 'FS' write subtables or 'ACC').
    All lane results are computed before any lane is written (operands may alias the destination)."""
    body = list(pre) + ['dm:1 = vudest;']
    for c in lanes:
        body.append(f'r{c}:4 = {exprs[c]};')
    for k, c in enumerate(XYZW):
        if c not in lanes:
            continue
        dst = f'vuACC{c}' if target == 'ACC' else f'W{target}{c}'
        body.append(f'if ((dm & {1 << (3 - k)}) == 0) goto <s{c}>; {dst} = r{c}; <s{c}>')
    return body


